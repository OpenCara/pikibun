// Embeds the sandbox's Python programs (apps/runner/src/sandbox-python/*.py) in the connector as
// apps/runner/src/sandbox-python.generated.ts, so every bundle (the CLI, the server's own runner) carries
// them without copying files next to it. The .py files are the source, linted and type-checked as Python
// (`pnpm python:check`); this writes the module (`pnpm python:embed`), and `--check` fails where it is out of date, as
// tests/sandbox-python.test.ts does.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const sources = join(root, "apps", "runner", "src", "sandbox-python");
const target = join(root, "apps", "runner", "src", "sandbox-python.generated.ts");

/** The programs, by the name the connector knows them by, and their file. */
const programs = [
  ["HELPER", "helper.py", "The sandbox's helper: every file operation and step of the Linux and macOS sandboxes (sandbox.ts, seatbelt.ts)."],
  ["GIT_SHIM", "git_shim.py", "The sandbox's git, in front of the real one, for clones that borrow the host's mirrors (see GIT_SHIM in sandbox.ts)."],
  ["BROWSER_DRIVER", "browser.py", "The browser tool's driver: the host's Chromium, headless, on a DevTools pipe, for one call (see browser-command.ts)."],
  ["SERVICE_DRIVER", "service.py", "The session service's driver: the session's web server, relayed from a Unix socket the connector shares (see session-service.ts)."],
];

export function embedded() {
  const parts = [
    "// Generated by scripts/embed-python.mjs from apps/runner/src/sandbox-python/*.py. Don't edit it: edit the .py file, then",
    "// run `pnpm python:embed`.",
  ];
  for (const [name, file, about] of programs) {
    parts.push("", `/** ${about} */`, `export const ${name}: string = ${JSON.stringify(readFileSync(join(sources, file), "utf8"))};`);
  }
  return `${parts.join("\n")}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const wanted = embedded();
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* not written yet */ }
  if (process.argv.includes("--check")) {
    if (current !== wanted) {
      console.error("apps/runner/src/sandbox-python.generated.ts is out of date: run `pnpm python:embed`.");
      process.exit(1);
    }
  } else if (current !== wanted) writeFileSync(target, wanted);
}
